-- 只建解析器依赖的表；保留唯一约束与索引，它们是角色基数规则的前提。
-- 合成结构，非业务数据副本。

CREATE TABLE t_user (
  ID BIGINT NOT NULL PRIMARY KEY,
  OPERATER_STATUS INT NOT NULL DEFAULT 1,
  ACCOUNT VARCHAR(64) NULL,
  PASSWORD VARCHAR(128) NULL,
  SALT VARCHAR(64) NULL
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;

CREATE TABLE t_staff (
  ID BIGINT NOT NULL PRIMARY KEY,
  TENANT_ID BIGINT NOT NULL,
  BELONG_USER_ID BIGINT NULL,
  DEPT_ID BIGINT NULL,
  OPERATER_STATUS INT NOT NULL DEFAULT 1,
  KEY IDX_STAFF_TENANT (TENANT_ID),
  KEY IDX_STAFF_USER (BELONG_USER_ID)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;

CREATE TABLE t_enterprise_role (
  ID BIGINT NOT NULL PRIMARY KEY,
  TENANT_ID BIGINT NOT NULL,
  OPERATER_STATUS INT NOT NULL DEFAULT 1
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;

CREATE TABLE t_enterprise_menu (
  ID BIGINT NOT NULL PRIMARY KEY,
  OPERATER_STATUS INT NOT NULL DEFAULT 1,
  CODE VARCHAR(128) NULL,
  NAME VARCHAR(128) NULL
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;

-- 唯一约束必须在位：角色基数规则以「一租户一用户至多一个角色」为前提。
CREATE TABLE tb_user_enterprise_role_tenant (
  ID BIGINT NOT NULL AUTO_INCREMENT PRIMARY KEY,
  TENANT_ID BIGINT NOT NULL,
  USER_ID BIGINT NOT NULL,
  ENTERPRISE_ROLE_ID BIGINT NOT NULL,
  UNIQUE KEY AK_KEY_1 (TENANT_ID, USER_ID)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;

CREATE TABLE tb_enterprise_role_menu_tenant (
  ID BIGINT NOT NULL AUTO_INCREMENT PRIMARY KEY,
  TENANT_ID BIGINT NOT NULL,
  ENTERPRISE_ROLE_ID BIGINT NOT NULL,
  ENTERPRISE_MENU_ID BIGINT NOT NULL,
  KEY IDX_RM_ROLE (ENTERPRISE_ROLE_ID)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;

CREATE TABLE t_project (
  ID BIGINT NOT NULL PRIMARY KEY,
  TENANT_ID BIGINT NOT NULL,
  PROJECT_NAME VARCHAR(255) NULL,
  PROJECT_MANAGER_NAMES VARCHAR(512) NULL,
  GENERAL_BUDGET DECIMAL(15,5) NULL,
  OPERATER_STATUS INT NOT NULL DEFAULT 1
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;

CREATE TABLE t_project_user (
  ID BIGINT NOT NULL PRIMARY KEY,
  TENANT_ID BIGINT NOT NULL,
  PROJECT_ID BIGINT NOT NULL,
  STAFF_ID BIGINT NOT NULL,
  OPERATER_STATUS INT NOT NULL DEFAULT 1,
  KEY IDX_PU_PROJECT (PROJECT_ID)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;
